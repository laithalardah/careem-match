def money(v):
    return {"discount": 0, "discount_percentage": 0, "original": v, "total": v}


def ids(r):
    n = r["id"] - 30100  # 6..13
    return n


def item_id(r, i):
    return int(f"70{ids(r):02d}{i:02d}")


def group_id(r, i, g):
    return int(f"9{ids(r):02d}{i}{g}")


def cuisines_json(r):
    return [{"id": cid, "name": n, "name_localized": n, "image_url": f"{CDN}/cuisines/{n.lower()}.jpg",
             "keywords": None, "keywords_localized": None} for cid, n in r["cuisines"]]


def flat_items(r):
    """[(index starting at 1, menu group index, dish tuple)]"""
    out, i = [], 0
    for gi, (_, dishes) in enumerate(r["menu"], 1):
        for d in dishes:
            i += 1
            out.append((i, gi, d))
    return out


def option_groups_menu(r, i, option_groups):
    res = []
    for g, (name, mn, mx, opts) in enumerate(option_groups, 1):
        gid = group_id(r, i, g)
        res.append({
            "id": gid, "name": name, "name_localized": name, "description": "", "description_localized": "",
            "active": True, "min": mn, "max": mx, "multi_select": mx > 1, "order": g,
            "options": [{"id": gid * 10 + k, "item": o, "item_localized": o, "is_active": True, "price": money(p)}
                        for k, (o, p) in enumerate(opts, 1)],
        })
    return res


