def search_scenarios():
    by_query = {}
    for r in EXTRA:
        for q in r["queries"]:
            by_query.setdefault(q, []).append(r)
    return [scenario(f"extra-{q}", f"`query` containing `{q}` → " + ", ".join(r["name"] for r in rs) + ".",
                     {"query": f"~{q}"}, {"page": "food_merchant_search", "restaurants": [search_entry(r) for r in rs]})
            for q, rs in by_query.items()]


def scenario(name, note, match, body):
    return (f"## Scenario: {name}\n\n{note}\n\n```json match\n{json.dumps(match, indent=2)}\n```\n\n"
            f"```json response\n{json.dumps(body, indent=2, ensure_ascii=False)}\n```\n\n")


def patch(path: Path, block: str):
    text = path.read_text(encoding="utf-8")
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", "", text, flags=re.S)
    if block:
        marker = "## Definition"
        i = text.index(marker)
        text = text[:i] + BEGIN + "\n\n" + block + END + "\n\n" + text[i:]
    path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    remove = "--remove" in sys.argv
    patch(TOOLS / "food_get_restaurant_menu.md", "" if remove else "".join(menu_scenario(r) for r in EXTRA))
    patch(TOOLS / "food_get_items_options.md", "" if remove else "".join(options_scenario(r) for r in EXTRA))
    patch(TOOLS / "food_merchant_search.md", "" if remove else "".join(search_scenarios()))
    print("removed the extra restaurants" if remove else f"added {len(EXTRA)} restaurants: " + ", ".join(r["name"] for r in EXTRA))
