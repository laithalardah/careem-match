def options_scenario(r):
    results = []
    for (i, _, (name, _desc, _price, ogs)) in flat_items(r):
        groups = []
        for g, (gname, mn, mx, opts) in enumerate(ogs, 1):
            gid = group_id(r, i, g)
            groups.append({
                "group_id": gid, "name": gname, "required": mn > 0, "min": mn, "max": mx, "multi_select": mx > 1,
                "options": [{"catalog_option_id": f"{gid}::{gid * 10 + k}", "group_id": gid, "option_id": gid * 10 + k,
                             "name": o, "price": p, "is_active": True} for k, (o, p) in enumerate(opts, 1)],
            })
        results.append({"item_id": item_id(r, i), "item_name": name, "has_required_options": any(g["required"] for g in groups),
                        "option_groups": groups})
    return scenario(r["slug"], f"Restaurant `{r['id']}` ({r['name']}): returns options for all of its menu items, whichever ids were asked for.",
                    {"restaurant_id": r["id"]}, {"page": "food_get_items_options", "results": results})


