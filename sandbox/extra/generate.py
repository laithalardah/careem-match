"""Adds the restaurants in restaurants.py to the sandbox tool files (menu, options, merchant search).

    py -3.12 sandbox/extra/generate.py            # (re)write the generated blocks
    py -3.12 sandbox/extra/generate.py --remove   # take them out again

Careem's original scenarios are never edited. Everything generated sits between BEGIN/END markers right before
each file's `## Definition`, so the script can rewrite or remove it any time. The server re-reads tool files on
every call, so no restart is needed (run `npm test` in sandbox/server to check the new scenarios).
"""
import json
